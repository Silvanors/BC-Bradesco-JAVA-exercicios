public class Pessoa {

    private final String name = "";
    private int age;
    private final String cpf = "";

    public Pessoa(String name, int age, String cpf) {
    }

    public String getName() {
        return name;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }

    public String getCpf() {
        return cpf;
    }
}
